#!/usr/bin/env python3
"""
wav_to_c.py - convert the pet's WAV sound effects into C arrays.

Each WAV is turned into 8-bit unsigned mono samples at SAMPLE_RATE Hz
(128 = silence), which sound.c plays out as PWM on the speaker pin.

Steps per file: stereo -> mono, resample (linear), trim quiet start/end,
normalize the loudness, convert to 0..255.

Uses only the Python standard library.
Run from the Project2_Virtual_Pet folder:
    python tools/wav_to_c.py
It rewrites App/Inc/sounds.h and App/Src/sounds.c - do not edit those by hand.
To add a sound (e.g. a purr), put the WAV in docs/audio and add a line to CLIPS.
"""
import os
import struct
import wave

SAMPLE_RATE = 8000          # Hz; must match SOUND_SAMPLE_RATE in sounds.h
TRIM_LEVEL  = 0.02          # samples quieter than 2% of max are "silence" at the ends
PEAK        = 0.95          # normalize the loudest sample to 95% of full scale

# (C name, file in docs/audio, what it is used for, options)
# Options for long sounds: "start"/"length" in seconds pick a piece of the file,
# "loop" blends the end into the start so the clip can repeat without a click.
CLIPS = [
    ("happy",  "mixkit-sweet-kitty-meow-93.wav",       "playing / happy"),
    ("hungry", "mixkit-angry-cartoon-kitty-meow-94.wav", "hungry or unhappy warning"),
    ("dead",   "mixkit-little-cat-pain-meow-87.wav",   "pet died"),
    ("meow",   "mixkit-cartoon-little-cat-meow-91.wav", "hello: power-up / new pet"),
    ("purr",   "bigsoundbank-cat-purr-0436.wav",       "sleeping (loops)",
               {"start": 0.5, "length": 2.5, "loop": True}),
]
LOOP_FADE = 0.15            # seconds of cross-fade for looping clips

ROOT    = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIO   = os.path.join(ROOT, "docs", "audio")
OUT_H   = os.path.join(ROOT, "App", "Inc", "sounds.h")
OUT_C   = os.path.join(ROOT, "App", "Src", "sounds.c")


def read_mono(path):
    """Return (samples in -1..1 as floats, sample rate)."""
    with wave.open(path, "rb") as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if width == 2:
        vals = struct.unpack("<%dh" % (len(raw) // 2), raw)
        scale = 32768.0
    elif width == 1:
        vals = [b - 128 for b in raw]
        scale = 128.0
    else:
        raise ValueError("%s: only 8- or 16-bit WAV supported" % path)
    mono = [sum(vals[i:i + ch]) / (ch * scale) for i in range(0, len(vals), ch)]
    return mono, rate


def resample(x, src_rate, dst_rate):
    """Linear interpolation resampler (good enough for short sound effects)."""
    n_out = int(len(x) * dst_rate / src_rate)
    out = []
    for i in range(n_out):
        pos = i * src_rate / dst_rate
        j = int(pos)
        frac = pos - j
        a = x[j]
        b = x[j + 1] if j + 1 < len(x) else a
        out.append(a + (b - a) * frac)
    return out


def cut(x, start, length):
    a = int(start * SAMPLE_RATE)
    return x[a:a + int(length * SAMPLE_RATE)]


def make_loop(x):
    """Cross-fade the last LOOP_FADE seconds into the first ones, then drop them,
    so jumping from the end back to the start is smooth."""
    n = int(LOOP_FADE * SAMPLE_RATE)
    head, body, tail = x[:n], x[n:len(x) - n], x[len(x) - n:]
    mixed = [tail[i] * (1 - i / n) + head[i] * (i / n) for i in range(n)]
    return mixed + body


def normalize(x):
    peak = max(abs(v) for v in x) or 1.0
    return [v * PEAK / peak for v in x]


def trim_and_normalize(x):
    peak = max(abs(v) for v in x) or 1.0
    thr = peak * TRIM_LEVEL
    start = next(i for i, v in enumerate(x) if abs(v) > thr)
    end = len(x) - next(i for i, v in enumerate(reversed(x)) if abs(v) > thr)
    x = x[start:end]
    gain = PEAK / peak
    return [v * gain for v in x]


def to_u8(x):
    return [max(0, min(255, int(round(128 + v * 127)))) for v in x]


def main():
    clips = []
    for entry in CLIPS:
        name, fname, use = entry[:3]
        opt = entry[3] if len(entry) > 3 else {}
        mono, rate = read_mono(os.path.join(AUDIO, fname))
        x = resample(mono, rate, SAMPLE_RATE)
        if "start" in opt:
            x = normalize(cut(x, opt["start"], opt["length"]))
        else:
            x = trim_and_normalize(x)
        if opt.get("loop"):
            x = make_loop(x)
        data = to_u8(x)
        clips.append((name, fname, use, data))
        print("%-7s %5d samples  %.2f s  (%s)" % (name, len(data), len(data) / SAMPLE_RATE, fname))

    with open(OUT_H, "w", newline="\n") as h:
        h.write("/**\n * @file    sounds.h\n * @brief   Pet sound clips: 8-bit unsigned mono PCM (128 = silence).\n")
        h.write(" *\n * GENERATED by tools/wav_to_c.py from the WAVs in docs/audio - do not edit.\n */\n")
        h.write("#ifndef SOUNDS_H\n#define SOUNDS_H\n\n#include <stdint.h>\n\n")
        h.write("#define SOUND_SAMPLE_RATE %du\n\n" % SAMPLE_RATE)
        h.write("typedef enum\n{\n")
        for i, (name, _, use, _) in enumerate(clips):
            h.write("  CLIP_%s%s,   /* %s */\n" % (name.upper(), " = 0" if i == 0 else "", use))
        h.write("  CLIP_COUNT\n} SoundClip;\n\n")
        h.write("extern const uint8_t * const sound_clip_data[CLIP_COUNT];\n")
        h.write("extern const uint32_t        sound_clip_len[CLIP_COUNT];\n\n#endif /* SOUNDS_H */\n")

    with open(OUT_C, "w", newline="\n") as c:
        c.write("/* GENERATED by tools/wav_to_c.py from the WAVs in docs/audio - do not edit. */\n")
        c.write('#include "sounds.h"\n\n')
        for name, fname, _, data in clips:
            c.write("/* %s (%d samples) */\n" % (fname, len(data)))
            c.write("static const uint8_t clip_%s[%d] = {\n" % (name, len(data)))
            for i in range(0, len(data), 16):
                c.write("  " + ",".join("%3d" % v for v in data[i:i + 16]) + ",\n")
            c.write("};\n\n")
        c.write("const uint8_t * const sound_clip_data[CLIP_COUNT] = {\n")
        c.write("".join("  clip_%s,\n" % n for n, _, _, _ in clips) + "};\n\n")
        c.write("const uint32_t sound_clip_len[CLIP_COUNT] = {\n")
        c.write("".join("  sizeof(clip_%s),\n" % n for n, _, _, _ in clips) + "};\n")
    print("wrote", os.path.relpath(OUT_H, ROOT), "and", os.path.relpath(OUT_C, ROOT))


if __name__ == "__main__":
    main()
